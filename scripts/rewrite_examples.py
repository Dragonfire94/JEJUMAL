def mix_pool(kind: str, verbs: list[str], comps: list[str]) -> list[tuple[str, str]]:
    out: list[tuple[str, str]] = []
    seen: set[str] = set()
    for comp in comps:
        for verb in verbs:
            tail = f"{comp} {verb}."
            if tail in seen:
                continue
            seen.add(tail)
            out.append((kind, tail))
    return out


