def take(pool: list[tuple[str, str]], used: set[str], seq: str = "") -> tuple[str, str]:
    for kind, tail in pool:
        if tail not in used:
            used.add(tail)
            return kind, tail
    raise RuntimeError(f"pool exhausted seq={seq} used={len(used)} pool={len(pool)}")



def attach_kind(lemma: str, kind: str) -> str:
    from assemble_examples import has_batchim, particle_for

    if kind == "none":
        return lemma
    particle = {
        "subj": "가",
        "obj": "를",
        "top": "는",
        "loc": "에",
        "from": "에서",
        "also": "도",
        "with": "와",
    }[kind]
    return lemma + particle_for(lemma, particle)


def korean_from(kind: str, lemma: str, tail: str) -> str:
    if "{w}" in tail:
        return tail.format(w=attach_kind(lemma, kind) if kind != "none" else lemma)
    if kind == "none":
        return f"{lemma} {tail}"
    return f"{attach_kind(lemma, kind)} {tail}"


