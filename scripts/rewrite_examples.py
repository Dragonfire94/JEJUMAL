def build_korean(word: dict, used: dict[str, set[str]], unit_id: str = "") -> str:
    seq = word["seq"]
    if seq in HAND:
        return HAND[seq][0]
    lemma = clean_lemma(word["standard"])
    bucket = classify(lemma, word["jeju"], unit_id)
    pool = POOLS[bucket]()
    kind, tail = take(pool, used.setdefault(bucket, set()), word["seq"])
    return korean_from(kind, lemma, tail)


def build_jeju(word: dict, korean: str, lex: dict[str, str]) -> str:
    seq = word["seq"]
    if seq in HAND:
        return HAND[seq][1]
    return jejuize(korean, lex, clean_lemma(word["standard"]), word["jeju"], word.get("partOfSpeech", ""))


def main() -> None:
    units = json.loads(UNITS_PATH.read_text(encoding="utf-8"))
    words = [w for u in units for w in u["words"]]
    lex = build_lexicon(words)
    used: dict[str, set[str]] = {}
    out: dict[str, list[dict]] = {}
    merged = []
    for unit in units:
        next_words = []
        for word in unit["words"]:
            item = dict(word)
            standard = build_korean(word, used, unit["id"])
            jeju = build_jeju(word, standard, lex)
            example = {"jeju": jeju, "standard": standard}
            item["examples"] = [example]
            out[word["seq"]] = [example]
            next_words.append(item)
        merged.append({**unit, "words": next_words})

    texts = [u["words"][i]["examples"][0]["jeju"] for u in merged for i in range(len(u["words"]))]
    dups = [t for t in texts if texts.count(t) > 1]
    meta = [t for t in texts if META_RE.search(t)]
    yo = []
    for unit in merged:
        for word in unit["words"]:
            jeju = word["examples"][0]["jeju"]
            for tok in ATOM_RE.findall(jeju):
                if tok != word["jeju"] and tok.endswith("요"):
                    yo.append((word["jeju"], jeju, tok))
                    break

    OUT_PATH.write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    UNITS_PATH.write_text(json.dumps(merged, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"words {len(out)} unique {len(set(texts))} dups {len(set(dups))} meta {len(meta)} yo {len(yo)}")
    print("used", {k: len(v) for k, v in sorted(used.items())})
    print("pool", {k: len(fn()) for k, fn in POOLS.items()})
    watch = ["하영", "각씨", "냄편", "옵서", "무사", "고장", "절간", "시기다", "하르방", "어멍", "아방", "하다", "조쟁이"]
    by = {w["jeju"]: w for u in merged for w in u["words"]}
    for name in watch:
        w = by.get(name)
        print(f"  {name}: {w['examples'][0] if w else 'n/a'}")
    for row in yo[:12]:
        print("  yo", row)
    leftover_report(merged)
    missing = [w["seq"] for w in words if w["seq"] not in out or not out[w["seq"]]]
    print("missing", missing[:8], "count", len(missing))


if __name__ == "__main__":
    main()


